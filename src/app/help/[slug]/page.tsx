export function generateStaticParams() {
  return Object.keys(PAGES).map((slug) => ({ slug }));
}

export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  return { title: PAGES[slug]?.title ?? "راهنما" };
}

export default async function HelpPage({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const page = PAGES[slug];
  if (!page) notFound();

  return (
    <div className="container-app py-6">
      <div className="mx-auto max-w-3xl">
        <nav className="mb-3 flex items-center gap-1 text-[12px] text-ink-500">
          <Link href="/" className="hover:text-brand-600">خانه</Link>
          <ChevronLeft className="size-3.5" />
          <span className="text-ink-800">{page.title}</span>
        </nav>

        <div className="rounded-2xl bg-white p-6 shadow-card lg:p-8">
          <h1 className="mb-4 text-xl font-bold text-ink-900">{page.title}</h1>
          <div className="space-y-4">
            {page.body.map((p, i) => (
              <p key={i} className="text-[13px] leading-8 text-ink-600">{p}</p>
            ))}
          </div>
        </div>

        <div className="mt-4 grid gap-2 sm:grid-cols-3">
          {Object.entries(PAGES)
            .filter(([s]) => s !== slug)
            .slice(0, 3)
            .map(([s, p]) => (
              <Link key={s} href={`/help/${s}`} className="rounded-xl bg-white p-4 text-[13px] text-ink-600 shadow-card hover:text-brand-600">
                {p.title}
              </Link>
            ))}
        </div>
      </div>
    </div>
  );
}
